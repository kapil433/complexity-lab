"""The 50 pre-specified playground experiments.

The text here is the scientific contract: hypothesis, null, method, variables,
and what a result must not be stretched to say. Executors live beside this
list and are rejected by tests if an id is missing.
"""

from __future__ import annotations

from complexity_lab.playground.models import ExperimentSpec, Knob

T_VALIDATE = "1. Data and system validation"
T_DESCRIBE = "2. Descriptive statistics"
T_ASSOCIATE = "3. Association and panel tests"
T_FORECAST = "4. Forecasts and scenarios"
T_COMPLEX = "5. Complexity science"


def _k(
    name: str,
    label: str,
    kind: str,
    default: object,
    minimum: float | int | None = None,
    maximum: float | int | None = None,
    step: float | int | None = None,
    help: str = "",
    options: tuple[str, ...] = (),
) -> Knob:
    return Knob(name, label, kind, default, minimum, maximum, step, help, options)


def _alpha() -> Knob:
    return _k(
        "alpha",
        "Significance level",
        "float",
        0.05,
        0.01,
        0.10,
        0.01,
        "The bar for rejecting a null. It does not create a causal claim.",
    )


def _years(start: int = 2015, end: int = 2025) -> tuple[Knob, Knob]:
    return (
        _k("year_start", "First year", "int", start, 2012, 2026, 1, "Inclusive calendar year."),
        _k(
            "year_end",
            "Last year",
            "int",
            end,
            2012,
            2026,
            1,
            "Inclusive. 2026 is a partial year and is flagged when included.",
        ),
    )


def _year(default: int = 2025) -> Knob:
    return _k("year", "Year", "int", default, 2012, 2026, 1, "Calendar year of the cross-section.")


