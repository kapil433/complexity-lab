def experiments() -> tuple[ExperimentSpec, ...]:
    return _EXPERIMENTS


def experiment_by_id(experiment_id: str) -> ExperimentSpec:
    for spec in _EXPERIMENTS:
        if spec.experiment_id == experiment_id:
            return spec
    known = ", ".join(spec.experiment_id for spec in _EXPERIMENTS)
    raise KeyError(f"Unknown playground experiment '{experiment_id}'. Known: {known}")
